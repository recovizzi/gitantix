// Generates src/overlay/icons.js from @primer/octicons and @gitlab/svgs (both MIT).
// render.js asks for icons by Octicon name; GITLAB maps those names to GitLab's own icons.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const OCTICONS = [
  'mark-github', 'three-bars', 'repo', 'code', 'issue-opened', 'git-pull-request', 'play', 'table', 'gear', 'graph', 'search',
  'triangle-down', 'people', 'copy', 'check', 'x', 'history', 'info', 'question', 'book', 'file', 'star', 'eye',
  'repo-forked', 'link-external', 'chevron-down', 'chevron-up', 'arrow-switch', 'git-commit', 'clock', 'light-bulb',
  'alert', 'sync', 'git-branch', 'tag', 'pulse', 'shield', 'sign-out', 'person-add', 'key', 'thumbsup', 'sort-desc',
  'paintbrush', 'globe', 'git-merge', 'check-circle-fill', 'x-circle-fill', 'unfold', 'fold', 'trophy', 'zap',
];
// octicon name (as used in render.js) → GitLab icon
const GITLAB = {
  tanuki: 'tanuki', sidebar: 'sidebar', 'three-bars': 'hamburger', repo: 'project', code: 'code', 'issue-opened': 'issues', 'git-pull-request': 'merge-request',
  play: 'rocket', table: 'work', gear: 'settings', graph: 'chart', search: 'search', 'triangle-down': 'chevron-down', people: 'users',
  copy: 'copy-to-clipboard', check: 'check', x: 'close', history: 'history', info: 'information-o', question: 'question-o',
  book: 'book', file: 'document', star: 'star-o', eye: 'eye', 'repo-forked': 'fork', 'link-external': 'external-link',
  'chevron-down': 'chevron-down', 'chevron-up': 'chevron-up', 'arrow-switch': 'retry', 'git-commit': 'commit', clock: 'clock',
  'light-bulb': 'bulb', alert: 'warning', sync: 'retry', 'git-branch': 'branch', tag: 'label', pulse: 'chart', shield: 'shield',
  'sign-out': 'leave', 'person-add': 'user', key: 'key', thumbsup: 'thumb-up', 'sort-desc': 'sort-highest', paintbrush: 'appearance',
  globe: 'earth', 'git-merge': 'git-merge', 'check-circle-fill': 'status_success', 'x-circle-fill': 'status_failed',
  unfold: 'expand', fold: 'collapse', trophy: 'star', zap: 'flag',
};

const out = { github: {}, gitlab: {} };
const missing = [];
for (const name of OCTICONS) {
  const f = path.join(root, `node_modules/@primer/octicons/build/svg/${name}-16.svg`);
  if (!fs.existsSync(f)) { missing.push(`octicon:${name}`); continue; }
  out.github[name] = fs.readFileSync(f, 'utf8').replace(/^<svg[^>]*>|<\/svg>\s*$/g, '').trim();
}
out.github.fallback = '<circle cx="8" cy="8" r="3"/>';

const sprite = fs.readFileSync(path.join(root, 'node_modules/@gitlab/svgs/dist/icons.svg'), 'utf8');
for (const [name, gl] of Object.entries(GITLAB)) {
  const m = sprite.match(new RegExp(`<symbol[^>]*id="${gl}"[^>]*>([\\s\\S]*?)</symbol>`));
  if (!m) { missing.push(`gitlab:${gl}`); continue; }
  out.gitlab[name] = m[1].trim();
}
out.gitlab.fallback = out.github.fallback;
// GitLab pages still show GitHub-named icons render.js asks for but GITLAB doesn't map: reuse the octicon.
for (const [k, v] of Object.entries(out.github)) out.gitlab[k] ??= v;

fs.writeFileSync(path.join(root, 'src/overlay/icons.js'),
  `// Generated by tools/icons-gen.mjs. Do not edit by hand.\n// Octicons (c) GitHub, Inc. and @gitlab/svgs (c) GitLab B.V., both MIT licensed.\nexport const icons = ${JSON.stringify(out)};\n`);
if (missing.length) console.warn('icons missing:', missing.join(', '));
console.log(`src/overlay/icons.js  ${Object.keys(out.github).length} octicons, ${Object.keys(GITLAB).length} gitlab`);
